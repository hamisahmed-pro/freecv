/** Friendly message when the Supabase provider isn't configured yet. */
export function oauthErrorMessage(provider: string, raw: string): string {
  if (/provider is not enabled|unsupported provider/i.test(raw)) {
    const name = provider === "linkedin_oidc" ? "LinkedIn" : "Google";
    return `${name} sign-in isn't connected yet — please use email for now.`;
  }
  return raw || "Sign-in failed";
}
